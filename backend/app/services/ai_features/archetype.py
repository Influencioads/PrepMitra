def _value(a: AttemptAnswer):
    return (a.answer or {}).get("value") if isinstance(a.answer, dict) else None


def _answered(a: AttemptAnswer) -> bool:
    v = _value(a)
    return v not in (None, "", [])


def _pct(n: int, d: int) -> int | None:
    return round(n * 100 / d) if d else None


def _clamp(v: float) -> int:
    return int(max(0, min(100, round(v))))


def _attempt_stats(answers: list[AttemptAnswer], qlen: dict) -> dict:
    """Raw counts for one or more attempts. Answers must be in paper order (seq) per attempt."""
    total = len(answers)
    done = [a for a in answers if _answered(a)]
    right = [a for a in done if a.is_correct]
    rushed = [a for a in done if 0 < (a.time_spent_sec or 0) < RUSHED_SEC]
    rushed_wrong = [a for a in rushed if not a.is_correct]
    long_q = [a for a in done if qlen.get(a.question_id, 0) >= LONG_CHARS]
    short_q = [a for a in done if qlen.get(a.question_id, 0) < SHORT_CHARS]
    return {"total": total, "attempted": len(done), "right": len(right), "wrong": len(done) - len(right),
            "rushed": len(rushed), "rushed_wrong": len(rushed_wrong),
            "rushed_wrong_long": sum(1 for a in rushed_wrong if qlen.get(a.question_id, 0) >= LONG_CHARS),
            "long": len(long_q), "long_right": sum(1 for a in long_q if a.is_correct),
            "long_seconds": round(statistics.mean([a.time_spent_sec or 0 for a in long_q])) if long_q else None,
            "short": len(short_q), "short_right": sum(1 for a in short_q if a.is_correct),
            "avg_seconds": round(statistics.mean([a.time_spent_sec or 0 for a in done])) if done else None}


def _sequence_stats(per_attempt: list[list[AttemptAnswer]]) -> dict:
    """Recovery (next 3 answers after a wrong one), first and last quarter accuracy."""
    after_n = after_right = first_n = first_right = last_n = last_right = 0
    for answers in per_attempt:
        done = [a for a in answers if _answered(a)]
        for i, a in enumerate(done):
            if a.is_correct is False:
                for b in done[i + 1:i + 4]:
                    after_n += 1
                    after_right += bool(b.is_correct)
        q = max(1, len(done) // 4)
        first_n += len(done[:q])
        first_right += sum(1 for a in done[:q] if a.is_correct)
        last_n += len(done[-q:]) if done else 0
        last_right += sum(1 for a in done[-q:] if a.is_correct)
    return {"after_wrong": _pct(after_right, after_n), "first_quarter": _pct(first_right, first_n),
            "last_quarter": _pct(last_right, last_n)}


def _traits(s: dict, seq: dict, scores: list[float]) -> dict:
    acc = _pct(s["right"], s["attempted"]) or 0
    attempt_rate = _pct(s["attempted"], s["total"]) or 0
    rushed_share = _pct(s["rushed"], s["attempted"]) or 0
    avg = s["avg_seconds"] or 40
    # Speed: blends the rushed share with average seconds (20 s or less scores high, 80 s or more low).
    speed = 0.5 * min(100, rushed_share * 3) + 0.5 * (100 - (min(80, max(20, avg)) - 20) * 100 / 60)
    stamina = 50 + ((seq["last_quarter"] or acc) - acc) * 2 + 20 if acc else 50
    recovery = 50 + ((seq["after_wrong"] if seq["after_wrong"] is not None else acc) - acc) * 2 + 25 if acc else 50
    if len(scores) >= 2:
        consistency = 100 - statistics.pstdev(scores) * 4 + (10 if scores[-1] >= scores[0] else -10)
    else:
        consistency = 60
    return {"speed": _clamp(speed), "accuracy": _clamp(acc), "risk": _clamp(attempt_rate),
            "stamina": _clamp(stamina), "recovery": _clamp(recovery), "consistency": _clamp(consistency)}


def _matches(traits: dict) -> list[dict]:
    out = []
    for key, p in PERSONAS.items():
        diff = statistics.mean(abs(traits[t] - p["shape"][t]) for t in TRAITS)
        out.append({"key": key, "match": _clamp(100 - diff)})
    return sorted(out, key=lambda m: -m["match"])


def _load(db: Session, user: User, limit: int = 10):
    attempts = db.scalars(select(Attempt).where(Attempt.user_id == user.id, Attempt.status == "scored",
                                                Attempt.max_score.is_not(None))
                          .order_by(Attempt.submitted_at.desc()).limit(limit)).all()
    attempts = list(reversed(attempts))  # oldest first
    ids = [a.id for a in attempts]
    rows = db.scalars(select(AttemptAnswer).where(AttemptAnswer.attempt_id.in_(ids))
                      .order_by(AttemptAnswer.attempt_id, AttemptAnswer.seq)).all() if ids else []
    by_attempt: dict = defaultdict(list)
    for r in rows:
        by_attempt[r.attempt_id].append(r)
    qids = {r.question_id for r in rows}
    qinfo = db.execute(select(Question.id, Question.text, Topic.name).join(Topic, Topic.id == Question.topic_id)
                       .where(Question.id.in_(qids))).all() if qids else []
    qlen = {q: len(t or "") for q, t, _ in qinfo}
    return attempts, by_attempt, qlen


def _evidence(s: dict, seq: dict, scores: list[int], n_mocks: int) -> list[dict]:
    acc = _pct(s["right"], s["attempted"])
    ev = []
    if s["rushed"]:
        net = s["rushed"] - s["rushed_wrong"]
        ev.append({"trait": "speed", "stat": f"{s['rushed']} in <{RUSHED_SEC}s",
                   "title": f"Answered {s['rushed']} questions in under {RUSHED_SEC} seconds — {s['rushed_wrong']} wrong",
                   "body": (f"{s['rushed_wrong_long']} of the {s['rushed_wrong']} wrong ones were long questions you "
                            f"skimmed. {net} of the rushed answers were right." if s["rushed_wrong"] else
                            "Every rushed answer was right. Speed is working for you."),
                   "marks": None})
    ev.append({"trait": "risk", "stat": f"{s['attempted']} / {s['total']}",
               "title": f"Attempted {_pct(s['attempted'], s['total'])}% of all questions across {n_mocks} "
                        f"mock{'s' if n_mocks != 1 else ''}",
               "body": "With 5 options and −0.25 per wrong answer, a blind guess is worth exactly 0 marks on average "
                       "(+1 × 1/5 − 0.25 × 4/5). Guess only after crossing out at least one option."})
    if seq["after_wrong"] is not None and acc is not None:
        ev.append({"trait": "recovery", "stat": f"{seq['after_wrong']}% vs {acc}%",
                   "title": f"After a wrong answer, your next 3 answers are {seq['after_wrong']}% right",
                   "body": f"Your overall accuracy is {acc}% ({s['right']} of {s['attempted']}). "
                           + ("A miss makes you rush the next few questions to win the time back."
                              if seq["after_wrong"] < acc else "You do not let one miss spoil the next questions.")})
    if seq["last_quarter"] is not None and acc is not None:
        ev.append({"trait": "stamina", "stat": f"{seq['last_quarter']}%",
                   "title": f"Last quarter of the paper held at {seq['last_quarter']}% accuracy",
                   "body": (f"Close to your {acc}% average. Stamina is not your problem."
                            if seq["last_quarter"] >= acc - 5 else
                            f"Below your {acc}% average. Practise full-length mocks to build stamina.")})
    if len(scores) >= 2:
        ev.append({"trait": "consistency", "stat": f"{scores[0]} → {scores[-1]}",
                   "title": f"Scores {', '.join(str(x) for x in scores)} across {len(scores)} mocks",
                   "body": "A clear climb." if scores[-1] > scores[0] else
                           "No climb yet. Change one habit at a time and keep the rest fixed."})
    if s["long"] and s["short"]:
        la, sa = _pct(s["long_right"], s["long"]), _pct(s["short_right"], s["short"])
        ev.append({"trait": "accuracy", "stat": f"{la}% vs {sa}%",
                   "title": f"Long questions: {la}% accuracy at {s['long_seconds']}s per question",
                   "body": f"Questions under two lines: {sa}%. "
                           + ("The gap is reading, not maths." if sa - la >= 10 else "Length does not hurt you.")})
    return ev


def _powers(traits: dict, s: dict, seq: dict, topics: list[dict]) -> tuple[list[dict], list[dict]]:
    acc = _pct(s["right"], s["attempted"]) or 0
    powers, spots = [], []
    if (seq["first_quarter"] or 0) >= acc:
        powers.append({"title": "Fearless start", "body": f"First-quarter accuracy is {seq['first_quarter']}%, at or "
                                                           f"above your {acc}% average."})
    if traits["stamina"] >= 65:
        powers.append({"title": "Full-paper stamina", "body": f"Accuracy holds at {seq['last_quarter']}% in the last "
                                                               "quarter of the paper."})
    if topics:
        best = max(topics, key=lambda t: t["mastery"])
        powers.append({"title": f"{best['topic']} on autopilot", "body": f"{best['mastery']}% mastery. Use it to bank "
                                                                         "time for harder sections."})
    if traits["accuracy"] >= 75:
        powers.append({"title": "Sharp aim", "body": f"{acc}% of your attempts are right."})
    if s["rushed_wrong"] >= 3:
        spots.append({"title": "Half-read questions", "body": f"{s['rushed_wrong']} wrong answers came in under "
                                                               f"{RUSHED_SEC} seconds."})
    if seq["after_wrong"] is not None and seq["after_wrong"] < acc - 5:
        spots.append({"title": "Chasing lost time", "body": f"After a miss, the next 3 answers fall to "
                                                             f"{seq['after_wrong']}%. Speeding up is the wrong reflex."})
    if topics:
        worst = min(topics, key=lambda t: t["mastery"])
        spots.append({"title": f"Weak spot: {worst['topic']}", "body": f"{worst['mastery']}% mastery across "
                                                                       f"{worst['attempted']} questions."})
    if traits["risk"] < 60:
        spots.append({"title": "Too many blanks", "body": f"Only {_pct(s['attempted'], s['total'])}% of questions "
                                                         "attempted."})
    return powers[:3], spots[:3]


def profile(db: Session, user: User, topics: list[dict] | None = None) -> dict:
    """The full persona page: traits, persona match, evidence, superpowers, blind spots, plan and history."""
    attempts, by_attempt, qlen = _load(db, user)
    personas = [{"key": k, **{f: p[f] for f in ("name", "tagline", "icon", "description", "signals", "shape")}}
                for k, p in PERSONAS.items()]
    if not attempts:
        return {"mocks_taken": 0, "persona": None, "traits": None, "matches": [], "personas": personas,
                "evidence": [], "superpowers": [], "blind_spots": [], "plan": [], "history": [], "answers": 0}
    per = [by_attempt[a.id] for a in attempts]
    flat = [x for xs in per for x in xs]
    s = _attempt_stats(flat, qlen)
    seq = _sequence_stats(per)
    scores = [round(a.score or 0) for a in attempts]
    pct_scores = [(a.score or 0) * 100 / a.max_score for a in attempts if a.max_score]
    traits = _traits(s, seq, pct_scores)
    matches = _matches(traits)
    top = matches[0]["key"]
    history = []
    for a, answers in zip(attempts, per):
        st = _attempt_stats(answers, qlen)
        sq = _sequence_stats([answers])
        k = _matches(_traits(st, sq, []))[0]["key"]
        history.append({"attempt_id": str(a.id), "date": a.submitted_at, "score": round(a.score or 0),
                        "max_score": round(a.max_score or 0), "persona": k, "persona_name": PERSONAS[k]["name"],
                        "attempted": st["attempted"], "right": st["right"], "wrong": st["wrong"],
                        "rushed": st["rushed"], "rushed_wrong": st["rushed_wrong"]})
    streak = 0
    for h in reversed(history):
        if h["persona"] != top:
            break
        streak += 1
    powers, spots = _powers(traits, s, seq, topics or [])
    return {
        "mocks_taken": len(attempts), "answers": s["attempted"], "persona": top, "traits": traits,
        "matches": matches, "match_percent": matches[0]["match"], "same_persona_streak": streak,
        "confidence": "high" if len(attempts) >= 4 and s["attempted"] >= 200 else
                      "medium" if len(attempts) >= 2 else "low",
        "personas": personas, "evidence": _evidence(s, seq, scores, len(attempts)),
        "superpowers": powers, "blind_spots": spots, "plan": PERSONAS[top]["plan"], "history": history,
    }
