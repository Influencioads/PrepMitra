/** Server-generated PDF (GET /v1/reports/{id}/pdf, needs the auth header, so fetched as a blob). */
async function downloadPdf(reportId: string, fileName: string) {
  const { data } = await http.get<Blob>(`/v1/reports/${reportId}/pdf`, { responseType: 'blob' });
  const url = URL.createObjectURL(data);
  const a = document.createElement('a');
  a.href = url;
  a.download = fileName;
  document.body.appendChild(a);
  a.click();
  a.remove();
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}

/** Why polling stopped: the report failed, it is taking too long, or the screen was closed. */
export class ReportPollError extends Error {
  constructor(
    public kind: 'failed' | 'timeout' | 'cancelled',
    message: string,
    public reportId?: string,
    public creditRestored?: boolean,
  ) {
    super(message);
  }
}

const esc = (s: string) => s.replace(/[&<>"]/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' })[c]!);

function downloadHtml(fileName: string, title: string, body: string) {
  const html = `<!doctype html><html><head><meta charset="utf-8"><title>${esc(title)}</title>
<style>body{font-family:"DM Sans",system-ui,sans-serif;color:#1C2321;max-width:820px;margin:32px auto;padding:0 16px;line-height:1.5}
h1{color:#C2410C}h2{border-bottom:1px solid #E3E2D8;padding-bottom:4px;margin-top:28px}table{border-collapse:collapse;width:100%}
td,th{border:1px solid #E3E2D8;padding:6px 8px;text-align:left;font-size:14px}.demo{background:#FFFBEB;border:1px solid #FDE68A;padding:8px 12px;border-radius:8px}</style>
</head><body>${body}<p style="color:#5B6661;font-size:12px;margin-top:32px">Generated by PrepMitra AI (prototype). Not affiliated with any exam-conducting body.</p></body></html>`;
  const blob = new Blob([html], { type: 'text/html' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = fileName;
  document.body.appendChild(a);
  a.click();
  a.remove();
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}

export const reportService = {
  /** GET /v1/attempts/{id}/report — returns 'processing' until the background job finishes. */
  async getReportStatus(attemptId: string): Promise<ReportStatusResponse> {
    const { data } = await http.get(API_ENDPOINTS.attemptReport(attemptId));
    if (data.status === 'ready') return { status: 'ready', report: mapExamReport(data, attemptId) };
    if (data.status === 'failed') {
      return {
        status: 'failed',
        reportId: data.id,
        creditRestored: !!data.credit_restored,
        message: data.error || (data.credit_restored ? 'Report generation failed. Your credit has been restored.' : 'Report generation failed.'),
      };
    }
    return { status: 'processing', progress: data.progress ?? undefined };
  },

  /**
   * Polls the report endpoint (every 3 s, plan Day 6) until it is ready.
   * A dropped network or a server hiccup (5xx) does not stop polling: `onNetwork(false)` is called and
   * the next tick tries again. Rejects on 'failed' (error has `reportId`), on timeout, or when the signal aborts.
   */
  async pollExamReport(
    attemptId: string,
    opts: {
      intervalMs?: number;
      timeoutMs?: number;
      signal?: AbortSignal;
      onProgress?: (p: number | undefined) => void;
      onNetwork?: (ok: boolean) => void;
    } = {},
  ): Promise<ExamReport> {
    const { intervalMs = 3000, timeoutMs = 120_000, signal, onProgress, onNetwork } = opts;
    const started = Date.now();
    for (;;) {
      if (signal?.aborted) throw new ReportPollError('cancelled', 'Report polling cancelled');
      let res: ReportStatusResponse | null = null;
      try {
        res = await reportService.getReportStatus(attemptId);
        onNetwork?.(true);
      } catch (e) {
        const status = (e as { status?: number })?.status ?? 0;
        if (status !== 0 && status < 500) throw e; // 404 / 409: retrying will not help
        onNetwork?.(false);
      }
      if (res?.status === 'ready') return res.report;
      if (res?.status === 'failed') throw new ReportPollError('failed', res.message, res.reportId, res.creditRestored);
      if (res) onProgress?.(res.progress);
      if (Date.now() - started + intervalMs > timeoutMs) {
        throw new ReportPollError('timeout', 'Your report is taking longer than usual. We will notify you when it is ready.');
      }
      await new Promise((r) => setTimeout(r, intervalMs));
    }
  },

  /** POST /v1/reports/{id}/retry — re-queue a failed report. */
  async retryReport(reportId: string): Promise<void> {
    await http.post(`/v1/reports/${reportId}/retry`);
  },

  /** POST /v1/reports/{id}/share — a public link valid for 30 days (no name, phone or questions on it). */
  async createShareLink(reportId: string): Promise<string> {
    const { data } = await http.post(`/v1/reports/${reportId}/share`);
    if (data.share_url) return data.share_url as string;
    throw new Error('The server did not return a share link.');
  },

  /** GET /v1/shared/reports/{token} — public view of a shared report (no login needed). */
  async getSharedReport(token: string): Promise<SharedReport> {
    if (USE_MOCK) throw Object.assign(new Error('Shared links work with the live backend.'), { status: 404 });
    const { data } = await http.get(`/v1/shared/reports/${encodeURIComponent(token)}`);
    return toSharedReport(data);
  },

  /** Server-generated PDF of the full report (real API). */
  downloadExamPdf: (r: ExamReport) => downloadPdf(r.id, `PrepMitra-${r.examId}-report.pdf`),

  /** POST /v1/reports/{id}/rating */
  async rate(reportId: string, rating: number): Promise<void> {
    if (!USE_MOCK) {
      await http.post(API_ENDPOINTS.reportRating(reportId), { rating });
      return;
    }
    await delay(300);
  },

  /** Production returns a server-generated PDF. The prototype downloads a printable HTML report. */
  downloadExamReport(r: ExamReport) {
    if (!USE_MOCK) return void downloadPdf(r.id, `PrepMitra-${r.examId}-report.pdf`);
    const rows = r.result.sections
      .map((s) => `<tr><td>${esc(s.name)}</td><td>${s.score}/${s.maxScore}</td><td>${s.correct}</td><td>${s.incorrect}</td><td>${s.unanswered}</td><td>${s.accuracy}%</td></tr>`)
      .join('');
    const weak = r.weaknesses.map((w) => `<li><b>${esc(w.topic)}</b> (${w.accuracy}%): ${esc(w.note)}</li>`).join('');
    const plan = r.improvementPlan.map((d) => `<li><b>Day ${d.day}: ${esc(d.title)}</b> — ${d.tasks.map(esc).join('; ')}</li>`).join('');
    const review = r.result.questions
      .map((q, i) => {
        const question = getQuestionById(q.questionId);
        return question ? `<li><b>Q${i + 1} (${q.outcome})</b> ${esc(question.text)}<br/><i>${esc(question.explanation)}</i></li>` : '';
      })
      .join('');
    downloadHtml(
      `PrepMitra-${r.examId}-report.html`,
      `${r.examTitle} — Report`,
      `<h1>${esc(r.examTitle)}</h1><p class="demo">Demo analysis generated from sample data on ${formatDate(r.createdAt)}.</p>
<p><b>Score:</b> ${r.result.score}/${r.result.maxScore} · <b>Accuracy:</b> ${r.result.accuracy}% · <b>Percentile (est.):</b> ${r.percentile} · <b>Time:</b> ${formatDuration(r.timeTakenSec)}</p>
<h2>Sections</h2><table><tr><th>Section</th><th>Score</th><th>Correct</th><th>Incorrect</th><th>Unanswered</th><th>Accuracy</th></tr>${rows}</table>
<h2>Strengths</h2><ul>${r.strengths.map((s) => `<li>${esc(s)}</li>`).join('')}</ul>
<h2>Weaknesses</h2><ul>${weak || '<li>No weak topics detected.</li>'}</ul>
<h2>7-day plan</h2><ol>${plan}</ol><h2>Question review</h2><ol>${review}</ol>`,
    );
  },

  downloadInterviewReport(r: InterviewReport) {
    if (!USE_MOCK) return void downloadPdf(r.id, `PrepMitra-interview-${r.roleId}.pdf`);
    const fb = r.questionFeedback
      .map((f) => `<li><b>${esc(f.question)}</b><br/>Your answer: ${esc(f.answer)}<br/>Good: ${esc(f.good)}<br/>Missing: ${esc(f.missing)}<br/><i>Model answer: ${esc(f.modelAnswer)}</i></li>`)
      .join('');
    const s = r.scores;
    downloadHtml(
      `PrepMitra-interview-${r.roleId}.html`,
      `${r.roleTitle} — Interview report`,
      `<h1>${esc(r.roleTitle)} — Interview report</h1><p class="demo">Demo evaluation generated by scripted rules on ${formatDate(r.createdAt)}.</p>
<table><tr><th>Role knowledge</th><th>Structure</th><th>Communication</th><th>Confidence</th><th>Resume consistency</th><th>Overall</th></tr>
<tr><td>${s.roleKnowledge}</td><td>${s.answerStructure}</td><td>${s.communication}</td><td>${s.confidence}</td><td>${s.resumeConsistency}</td><td><b>${r.overall}</b></td></tr></table>
<h2>Strengths</h2><ul>${r.strengths.map((x) => `<li>${esc(x)}</li>`).join('')}</ul>
<h2>Areas to improve</h2><ul>${r.weaknesses.map((x) => `<li>${esc(x)}</li>`).join('')}</ul>
<h2>Question feedback</h2><ol>${fb}</ol>`,
    );
  },
};
